package io.github.zhoutaoq.shadowflow.biz.store;

/**
 * 「把磁盘上的数据重新载入内存」。
 *
 * <p>只有文件模式的仓储需要它：它们在启动 {@code @PostConstruct} 时把整份数据载进内存，
 * 之后读写都走内存 + 写穿到文件。数据迁移导入是<b>唯一</b>绕过仓储直接改文件的场景，
 * 改完必须让这些仓储重读一遍，否则页面看到的还是导入前的旧值，
 * 下一次业务写入还会拿内存里的旧快照把刚导进来的数据盖回去。
 *
 * <p>数据库模式的仓储不实现本接口 —— 它们每次现查，没有内存快照。
 */
public interface Reloadable {

    /** 重新从磁盘载入；实现必须幂等，且要把 id 游标一起推到文件里的最大值 */
    void reloadData();
}
